"""Distributional measurement estimator — the project's core contribution (B.4).

This estimator computes the **multi-level tail-risk feedback** — six left-tail
scalars (cvar_05/10/25/01, left_tail_mass, robust_skew) — that the LLM
reward-designer is fed in the tail-feedback arm. It is a **critic-agnostic
post-hoc estimator**: it reads no Q-network and fits only on *realized* portfolio
returns (audit A-1). "Critic-agnostic" means architecture-independent (SAC mean
critic, TQC quantile critic, anything) — it does NOT mean agent-independent: the
returns it fits are the trained policy's OWN realized returns under the candidate
reward (see the endogeneity note below). It is computed on the **training-period**
realized **simple** (arithmetic, per-step) portfolio returns (audit B-2):
measuring on validation and then selecting on validation would re-introduce
overfitting, so the LLM shapes the in-sample tail while the agent is judged
out-of-sample.

The fed signal is endogenous to the agent (honest disclosure). The estimator is
fit on the returns generated by the SAC policy that was itself trained under the
candidate reward (call path: ``llm.loop`` trains the policy, then
``EnvBundle.train_returns(policy)`` rolls THAT policy and the estimator fits its
realized ``info["port_ret"]`` series). H2 is therefore a comparison of two coupled
reward -> policy -> measurement loops (scalar-fed vs tail-fed): the fed
distribution is shaped by the very agent it steers, which is the legitimate object
of study (does richer tail feedback steer a better reward-and-policy?), not an
exogenous risk measurement. The train/val split mitigates selection-overfitting
(fed in-sample, scored out-of-sample) but does NOT break this endogeneity — no
claim of an agent-independent / "works on any agent" tail measurement is made.

Estimator design (FINAL_PLAN F.2, B.4, audit B-1):
  - EMPIRICAL is PRIMARY for the body of the distribution (CVaR / quantiles /
    left-tail mass / robust skew) — for a 1-D sample the empirical quantile is the
    efficient estimator. Used for alpha in {25%, 10%}.
  - GENERALIZED-PARETO / EVT tail fit (per EX-DRL) for the extreme levels
    (CVaR-5%, CVaR-1%): the tail holds only ~7-37 observations, so an EVT fit makes
    those signals estimable rather than sample-noise. A neural quantile network is
    NOT used for the headline statistics.
  - left_tail_mass and robust_skew are derived from empirical quantiles (B.10).

Frozen tail-diagnostic set (returned by `tail_stats`, exactly these keys):
  cvar_01, cvar_05, cvar_10, cvar_25, left_tail_mass, robust_skew.
  cvar_01 is RETAINED BUT EXPLICITLY FLAGGED HIGH-VARIANCE (audit B-7); it is the
  EVT-estimated extreme and must be documented as such wherever it is reported.

EVT-tail CVaR derivation (peaks-over-threshold). Working on losses ``L = -returns``
with a high threshold ``u`` (the empirical loss-quantile at ``threshold_q``), the
exceedances ``Y = L - u | L > u`` follow a Generalized-Pareto law GPD(xi, beta).
With tail probability ``p`` (= ``alpha``) and tail-exceedance fraction
``F_u = P(L > u)`` the loss Value-at-Risk and Conditional VaR are::

    VaR_p  = u + (beta / xi) * ((p / F_u) ** (-xi) - 1)            (xi != 0)
    CVaR_p = (VaR_p + beta - xi * u) / (1 - xi)                    (xi < 1)

and the (signed) return-space CVaR reported to callers is ``-CVaR_p``. The closed
form is only used inside the **regular MLE region** ``-0.5 < xi < 1``: for ``xi >= 1``
the tail has infinite mean (CVaR undefined) and for ``xi <= -0.5`` the GPD MLE is
non-regular (Smith 1985, Biometrika 72(1): the likelihood loses its standard root-n /
asymptotic-normal behaviour), so OUTSIDE that open interval ``_evt_cvar`` falls back to
the empirical CVaR (see :data:`EVT_NONREGULAR_XI_NOTE`). On the small-sample shapes fitted here (the
downward-biased MLE sits inside the regular interval, not the true loss tail) both
guards fire essentially never; they are defensive.

GPD parameter estimation — PLAIN MAXIMUM LIKELIHOOD (no bias correction).
``(xi, beta)`` are fitted by **plain maximum likelihood** via
``scipy.stats.genpareto.fit`` (the McNeil-Frey-Embrechts 2005 §7.2.3 POT estimator;
``fit`` is unmodified MLE — it carries no small-sample bias correction). On few
exceedances the GPD MLE is known to be biased and high-variance (Giles; arXiv
2007.10780). The **bias-corrected / unbiased POT estimator (UPOT) of Troop, Godin &
Yu, 2021 (arXiv:2103.05059) is NOT implemented here — it is FUTURE WORK**, for the
following first-hand-measured reasons (do not over-read this estimator as bias-corrected):

  * Troop UPOT corrects two BIAS sources (GPD-approximation error, eq. 17-18, and
    MLE parameter bias, eq. 14) via second-order regular-variation machinery: a
    Fraga-Alves (2003) rho-hat (adaptive ADARHO selection) and a Hill-moment A-hat
    (eq. 22). That machinery requires a **heavy** tail (xi > 0; the Hill estimator
    underlying rho-hat / A-hat is only consistent for xi > 0) and is validated by the
    authors only at **n in [5e3, 5e4] and alpha in {0.998, 0.999}** with threshold
    percentiles 0.79-0.98 (their Tables 1-2).
  * This estimator's regime is the OPPOSITE corner: measured at n~750 training returns
    (the pre-Split-C fed window), alpha in {0.05, 0.01}, threshold_q=0.10 (~75
    exceedances). The EXECUTED Split-C fed window is the full train rollout ~2,961
    sessions => ~296 exceedances at threshold_q=0.10 and ~30 cvar_01 tail points —
    direction unchanged, the estimator strictly better-fed. Measured here (replayable):
    (a) the plain-MLE CVaR error at n=750 is ~98% VARIANCE, ~2-6% bias (CVaR-5% bias
    ~ -0.1%, CVaR-1% bias ~ +0.9% of the true value) — UPOT corrects bias, not
    variance, so it cannot help the dominant error term; and (b) on these portfolio
    losses the small-sample GPD MLE returns xi <= 0 in ~94% of n=750 draws (a downward-bias
    artefact at ~75 exceedances, NOT a genuinely light tail),
    where the rho-hat / A-hat correction is UNDEFINED (A-hat's denominator
    2*xi_MLE*rho_hat*M1 -> 0) and ill-conditioned (|A-hat| > 5 or NaN otherwise).
    A faithful UPOT would therefore NO-OP (fall back to MLE/empirical) in the vast
    majority of cases and inject instability in the rest — strictly worse RMSE here.
  * Accompanying stability exhibit: ``threshold_sensitivity`` reports the POT
    bias-variance spread of the fed CVaR levels across thresholds (the honest
    diagnostic shipped in lieu of the correction).

Audit refs: B-1 (empirical primary + EVT tails), B-2 (measure on training returns),
B-7 (CVaR-1% kept-but-flagged); see also DEEP_H2 sec. 6.2 / PREREGISTRATION sec. 4.
"""

